def test_validator_executes_only_from_trusted_root(tmp_path: Path):
    """C02: Ensure LocalValidator resolves validator scripts from trusted_root, not untrusted worktree."""
    trusted_root = tmp_path / "trusted_repo"
    trusted_scripts = trusted_root / "scripts"
    trusted_scripts.mkdir(parents=True)

    # Create real harmless scripts in trusted root
    (trusted_scripts / "check-windows-footguns.py").write_text("import sys; sys.exit(0)", encoding="utf-8")
    (trusted_scripts / "secret_scanner.py").write_text("import sys; sys.exit(0)", encoding="utf-8")

    # Create hostile trap in untrusted worktree
    untrusted_worktree = tmp_path / "untrusted_worktree"
    untrusted_scripts = untrusted_worktree / "scripts"
    untrusted_scripts.mkdir(parents=True)
    trap_file = tmp_path / "host_pwned.marker"
    hostile_code = f"import sys, pathlib; pathlib.Path(r'{trap_file}').write_text('PWNED'); sys.exit(0)"
    (untrusted_scripts / "check-windows-footguns.py").write_text(hostile_code, encoding="utf-8")
    (untrusted_scripts / "secret_scanner.py").write_text(hostile_code, encoding="utf-8")

    validator = LocalValidator()
    with patch.object(LocalValidator, "run_diff_check", return_value=(True, "")):
        overall_ok, results = validator.run_validation(untrusted_worktree, trusted_root=trusted_root)

    # Trap file must NOT exist
    assert not trap_file.exists()
    assert results.get("windows_footguns") == "PASS"
    assert results.get("secret_scanner") == "PASS"


