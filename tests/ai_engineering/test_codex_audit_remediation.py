def test_restore_quick_snapshot_validates_db_integrity(tmp_path: Path):
    """H10: Ensure restore_quick_snapshot validates SQLite integrity before atomic replacement."""
    home = tmp_path / "hermes_home"
    home.mkdir()
    valid_db = home / "state.db"

    # Pre-create a valid DB at destination
    with sqlite3.connect(valid_db) as conn:
        conn.execute("CREATE TABLE t (id INT);")

    snap_dir = home / "state-snapshots" / "snap-bad-db"
    snap_dir.mkdir(parents=True)
    (snap_dir / "state.db").write_text("NOT A REAL SQLITE DATABASE", encoding="utf-8")
    manifest = {"files": {"state.db": 26}}
    (snap_dir / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")

    # Restore must reject bad DB and keep valid DB intact
    restored = restore_quick_snapshot("snap-bad-db", hermes_home=home)
    assert restored is False

    # Check original valid DB is still intact
    with sqlite3.connect(valid_db) as conn:
        res = conn.execute("PRAGMA integrity_check").fetchall()
        assert res == [("ok",)]


